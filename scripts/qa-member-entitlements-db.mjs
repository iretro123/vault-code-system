// Isolated SQL/RLS tests. No live backend, user records, or payment operations.
import { readFile } from 'node:fs/promises';
import { pathToFileURL } from 'node:url';
import assert from 'node:assert/strict';
const { PGlite } = await import(pathToFileURL(process.argv[2]).href);
const db = new PGlite();
await db.exec(`
CREATE ROLE authenticated; CREATE ROLE anon; CREATE ROLE service_role;
CREATE SCHEMA auth;
CREATE FUNCTION auth.uid() RETURNS uuid LANGUAGE sql STABLE AS $$ SELECT nullif(current_setting('request.jwt.claim.sub',true),'')::uuid $$;
GRANT USAGE ON SCHEMA auth TO authenticated,anon;
CREATE TABLE auth.users(id uuid PRIMARY KEY,email text,created_at timestamptz DEFAULT now());
CREATE TABLE profiles(user_id uuid PRIMARY KEY,is_banned boolean DEFAULT false,access_status text DEFAULT 'active',updated_at timestamptz);
CREATE TABLE allowed_signups(email text);
CREATE TABLE user_roles(user_id uuid,role text,subscription_status text,access_source text);
CREATE TABLE academy_roles(id uuid,name text);
CREATE TABLE academy_user_roles(user_id uuid,role_id uuid);
CREATE TABLE students(id uuid PRIMARY KEY,auth_user_id uuid,stripe_customer_id text,created_at timestamptz DEFAULT now());
CREATE TABLE student_access(user_id uuid,product_key text,tier text,status text,stripe_subscription_id text,stripe_customer_id text,is_lifetime boolean,updated_at timestamptz DEFAULT now());
CREATE TABLE ios_membership_activations(user_id uuid,expires_date timestamptz,metadata jsonb);
CREATE TABLE android_membership_activations(user_id uuid,expires_date timestamptz,subscription_state text);
CREATE TABLE academy_messages(room_slug text,body text);
CREATE TABLE academy_lessons(module_slug text,video_url text);
CREATE TABLE live_sessions(join_url text);
CREATE TABLE academy_notifications(user_id uuid,type text,title text,body text,link_path text);
ALTER TABLE academy_notifications ENABLE ROW LEVEL SECURITY;
GRANT SELECT ON academy_notifications TO authenticated,anon;
CREATE POLICY old_notifications ON academy_notifications FOR SELECT USING(true);
ALTER TABLE academy_messages ENABLE ROW LEVEL SECURITY;
ALTER TABLE academy_lessons ENABLE ROW LEVEL SECURITY;
ALTER TABLE live_sessions ENABLE ROW LEVEL SECURITY;
GRANT SELECT,INSERT ON academy_messages,academy_lessons,live_sessions TO authenticated,anon;
CREATE POLICY old_messages ON academy_messages FOR ALL USING(true) WITH CHECK(true);
CREATE POLICY old_lessons ON academy_lessons FOR ALL USING(true) WITH CHECK(true);
CREATE POLICY old_live ON live_sessions FOR ALL USING(true) WITH CHECK(true);
INSERT INTO academy_messages VALUES('trade-floor','free'),('daily-setups','paid'),('future-paid-room','private');
INSERT INTO academy_lessons VALUES('chapter-1-basic-bridge','free-video'),('paid-chapter','paid-video');
INSERT INTO live_sessions VALUES('private-room-link');
`);
await db.exec(await readFile(new URL('../supabase/migrations/20260928000100_canonical_member_entitlements.sql',import.meta.url),'utf8'));
const uid='00000000-0000-0000-0000-000000000001';
await db.query("INSERT INTO auth.users(id,email) VALUES($1,'Member@Example.com')",[uid]);
await db.query('INSERT INTO profiles(user_id) VALUES($1)',[uid]);
await db.query("INSERT INTO students(id,auth_user_id,stripe_customer_id) VALUES($1,$1,'cus_member')",[uid]);
await db.query("INSERT INTO user_roles VALUES($1,'vault_access','active','stripe')",[uid]);
let checks=0;
async function check(name,allowed) {
  await db.query("SELECT set_config('request.jwt.claim.sub',$1,false)",[uid]);
  await db.exec('SET ROLE authenticated');
  assert.equal((await db.query('SELECT has_current_full_access() AS allowed')).rows[0].allowed,allowed,name);
  assert.equal((await db.query('SELECT * FROM get_my_access_state()')).rows[0].has_access,allowed,`${name}: RPC`);
  assert.equal((await db.query("SELECT * FROM academy_messages WHERE room_slug='daily-setups'")).rows.length,allowed?1:0,`${name}: paid messages`);
  assert.equal((await db.query("SELECT * FROM academy_messages WHERE room_slug='future-paid-room'")).rows.length,allowed?1:0,`${name}: new room defaults paid`);
  assert.equal((await db.query("SELECT * FROM academy_lessons WHERE module_slug='paid-chapter'")).rows.length,allowed?1:0,`${name}: paid videos`);
  assert.equal((await db.query('SELECT * FROM live_sessions')).rows.length,allowed?1:0,`${name}: room links`);
  await db.exec('RESET ROLE');
  checks+=6;
  console.log(`PASS: ${name}`);
}
await check('A stale paid role alone cannot grant access',false);
await db.query("INSERT INTO allowed_signups VALUES(' member@example.COM ')");
await check('Whitelist grants full access without billing rows',true);
await db.query("INSERT INTO student_access VALUES($1,'vault_os','full_access','canceled','sub_1','cus_member',false,now())",[uid]);
await check('Stripe cancellation cannot revoke a whitelist member',true);
await db.query('DELETE FROM allowed_signups');
await check('Removing whitelist reveals canceled subscription despite stale role',false);
await db.query("INSERT INTO academy_notifications VALUES($1,'announcement','Signal','secret','/academy/community?tab=daily-setups')",[uid]);
assert.equal((await db.query('SELECT * FROM academy_notifications')).rows.length,0,'No new paid push for expired member');
for(const status of ['active','trialing','past_due','unpaid','paused','incomplete','canceled']) {
  await db.query('UPDATE student_access SET status=$1',[status]);
  await check(`Stripe status ${status}`,status==='active');
}
await db.query("UPDATE student_access SET status='active',stripe_subscription_id=null,is_lifetime=true");
await check('Manual/lifetime row without Stripe is not a whitelist',false);
await db.query("INSERT INTO ios_membership_activations VALUES($1,now()+interval '1 day','{\"apple_verified\":true}')",[uid]);
await check('Verified unexpired Apple purchase grants access',true);
await db.query("UPDATE ios_membership_activations SET expires_date=now()-interval '1 second'");
await check('Expired Apple purchase cannot grant access',false);
await db.query("UPDATE ios_membership_activations SET expires_date=now()+interval '1 day',metadata='{}'");
await check('Unverified Apple record cannot grant access',false);
await db.query("INSERT INTO android_membership_activations VALUES($1,now()+interval '1 day','SUBSCRIPTION_STATE_ACTIVE')",[uid]);
await check('Active verified-store record preserves Google Play access',true);
await db.query("UPDATE android_membership_activations SET expires_date=now()-interval '1 second'");
await check('Expired store purchase returns to free',false);
await db.query("INSERT INTO allowed_signups VALUES('member@example.com')");
await db.query('UPDATE profiles SET is_banned=true');
await check('Ban overrides whitelist',false);
await db.query("SELECT grant_whitelist_access('member@example.com')");
assert.equal((await db.query('SELECT is_banned FROM profiles')).rows[0].is_banned,true);
await db.query('UPDATE profiles SET is_banned=false');
await db.query('DELETE FROM allowed_signups');
await db.exec('SET ROLE authenticated');
assert.equal((await db.query("SELECT * FROM academy_messages WHERE room_slug='trade-floor'")).rows.length,1);
assert.equal((await db.query("SELECT * FROM academy_lessons WHERE module_slug='chapter-1-basic-bridge'")).rows.length,1);
await assert.rejects(()=>db.query("INSERT INTO academy_messages VALUES('daily-setups','bypass')"));
await db.query("INSERT INTO academy_messages VALUES('trade-floor','allowed')");
await assert.rejects(()=>db.query('SELECT vault_access_for_user($1)',[uid]));
await db.exec('RESET ROLE');
const staff='00000000-0000-0000-0000-000000000002';
await db.query("INSERT INTO auth.users(id,email) VALUES($1,'staff@example.com')",[staff]);
await db.query('INSERT INTO profiles(user_id) VALUES($1)',[staff]);
await db.query("INSERT INTO user_roles VALUES($1,'operator','active','staff')",[staff]);
await db.query("SELECT set_config('request.jwt.claim.sub',$1,false)",[staff]);
await db.exec('SET ROLE authenticated');
await db.query("SELECT create_mention_notifications('Coach','daily-setups','private alert',ARRAY[]::uuid[],true)");
await db.exec('RESET ROLE');
const recipients=(await db.query('SELECT user_id FROM academy_notifications')).rows;
assert.deepEqual(recipients.map(r=>r.user_id),[staff],'Paid everyone alert targets only current entitlements, never broadcast');
await db.query("SELECT set_config('request.jwt.claim.sub',$1,false)",[uid]);
await db.exec('SET ROLE authenticated');
assert.equal((await db.query('SELECT * FROM academy_notifications')).rows.length,0,'Expired users cannot read paid notification content');
await assert.rejects(()=>db.query("SELECT create_mention_notifications('Member','daily-setups','private',ARRAY[]::uuid[],false)"));
await db.exec('RESET ROLE');
await db.query("SELECT set_config('request.jwt.claim.sub','',false)");
await db.exec('SET ROLE anon');
assert.equal((await db.query('SELECT * FROM academy_messages')).rows.length,0);
assert.equal((await db.query('SELECT * FROM academy_lessons')).rows.length,0);
await db.close();
console.log(`PASS: ${checks} entitlement/RLS assertions plus free reads/writes, paid write denial, private helper and anonymous checks.`);
