// Isolated SQL/RLS tests. No live backend, user records, or payment operations.
import { readFile } from 'node:fs/promises';
import { pathToFileURL } from 'node:url';
import assert from 'node:assert/strict';
const { PGlite } = await import(pathToFileURL(process.argv[2]).href);
const db = new PGlite();
await db.exec(`
CREATE ROLE authenticated; CREATE ROLE anon; CREATE ROLE service_role;
CREATE SCHEMA auth;
CREATE FUNCTION auth.uid() RETURNS uuid LANGUAGE sql STABLE AS $$ SELECT nullif(current_setting('request.jwt.claim.sub',true),'')::uuid $$;
GRANT USAGE ON SCHEMA auth TO authenticated,anon;
CREATE TABLE auth.users(id uuid PRIMARY KEY,email text,created_at timestamptz DEFAULT now());
CREATE TABLE profiles(user_id uuid PRIMARY KEY,is_banned boolean DEFAULT false,access_status text DEFAULT 'active',updated_at timestamptz);
CREATE TABLE allowed_signups(email text);
CREATE TABLE user_roles(user_id uuid,role text,subscription_status text,access_source text);
CREATE TABLE academy_roles(id uuid,name text);
CREATE TABLE academy_user_roles(user_id uuid,role_id uuid);
CREATE TABLE students(id uuid PRIMARY KEY,auth_user_id uuid,stripe_customer_id text,created_at timestamptz DEFAULT now());
CREATE TABLE student_access(user_id uuid,product_key text,tier text,status text,stripe_subscription_id text,stripe_customer_id text,is_lifetime boolean,updated_at timestamptz DEFAULT now());
CREATE TABLE ios_membership_activations(user_id uuid,expires_date timestamptz,metadata jsonb);
CREATE TABLE android_membership_activations(user_id uuid,expires_date timestamptz,subscription_state text);
CREATE TABLE academy_messages(room_slug text,body text);
CREATE TABLE academy_lessons(module_slug text,video_url text);
CREATE TABLE live_sessions(join_url text);
CREATE TABLE academy_notifications(user_id uuid,type text,title text,body text,link_path text);
ALTER TABLE academy_notifications ENABLE ROW LEVEL SECURITY;
GRANT SELECT ON academy_notifications TO authenticated,anon;
CREATE POLICY old_notifications ON academy_notifications FOR SELECT USING(true);
ALTER TABLE academy_messages ENABLE ROW LEVEL SECURITY;
ALTER TABLE academy_lessons ENABLE ROW LEVEL SECURITY;
ALTER TABLE live_sessions ENABLE ROW LEVEL SECURITY;
GRANT SELECT,INSERT ON academy_messages,academy_lessons,live_sessions TO authenticated,anon;
CREATE POLICY old_messages ON academy_messages FOR ALL USING(true) WITH CHECK(true);
CREATE POLICY old_lessons ON academy_lessons FOR ALL USING(true) WITH CHECK(true);
CREATE POLICY old_live ON live_sessions FOR ALL USING(true) WITH CHECK(true);
INSERT INTO academy_messages VALUES('trade-floor','free'),('daily-setups','paid'),('future-paid-room','private');
INSERT INTO academy_lessons VALUES('chapter-1-basic-bridge','free-video'),('paid-chapter','paid-video');
INSERT INTO live_sessions VALUES('private-room-link');
`);
await db.exec(await readFile(new URL('../supabase/migrations/20260928000100_canonical_member_entitlements.sql',import.meta.url),'utf8'));

await db.exec(`
ALTER TABLE academy_messages ADD COLUMN id uuid PRIMARY KEY DEFAULT gen_random_uuid(), ADD COLUMN user_id uuid, ADD COLUMN user_name text DEFAULT 'Member', ADD COLUMN is_deleted boolean DEFAULT false, ADD COLUMN created_at timestamptz DEFAULT now();
ALTER TABLE academy_notifications ADD COLUMN id uuid PRIMARY KEY DEFAULT gen_random_uuid();
CREATE TABLE user_preferences(user_id uuid PRIMARY KEY,notifications_enabled boolean DEFAULT true,notify_live_events boolean DEFAULT true);
CREATE TABLE device_tokens(id uuid PRIMARY KEY DEFAULT gen_random_uuid(),user_id uuid,platform text,token text);
CREATE TABLE pulse_spy_events(id text PRIMARY KEY,at bigint,timeframe text,body jsonb);
CREATE SCHEMA vault; CREATE TABLE vault.decrypted_secrets(name text,decrypted_secret text);
CREATE SCHEMA net; CREATE FUNCTION net.http_post(url text,headers jsonb,body jsonb,timeout_milliseconds integer) RETURNS bigint LANGUAGE sql AS $$ SELECT 1::bigint $$;
CREATE SCHEMA cron; CREATE FUNCTION cron.schedule(text,text,text) RETURNS bigint LANGUAGE sql AS $$ SELECT 1::bigint $$;
`);
await db.exec(await readFile(new URL('../supabase/migrations/20260928000200_chat_only_push.sql',import.meta.url),'utf8'));
await db.exec('CREATE TRIGGER push_notify_on_insert AFTER INSERT ON academy_notifications FOR EACH ROW EXECUTE FUNCTION public.push_notify_on_insert()');
await db.exec(await readFile(new URL('../supabase/migrations/20260929000100_reliable_chat_pulse_delivery.sql',import.meta.url),'utf8'));
const ids=Array.from({length:5},(_,i)=>`00000000-0000-0000-0000-${String(i+1).padStart(12,'0')}`);
const [sender,free,paid,muted,banned]=ids;
for (const [i,id] of ids.entries()) {
 await db.query('INSERT INTO auth.users(id,email) VALUES($1,$2)',[id,`member${i}@example.com`]);
 await db.query('INSERT INTO profiles(user_id,is_banned) VALUES($1,$2)',[id,id===banned]);
 await db.query('INSERT INTO user_preferences(user_id,notifications_enabled) VALUES($1,$2)',[id,id!==muted]);
 await db.query("INSERT INTO device_tokens(user_id,platform,token) VALUES($1,'ios:test',$2)",[id,id]);
}
await db.query("INSERT INTO allowed_signups VALUES('member2@example.com')");
await db.query("INSERT INTO user_roles(user_id,role) VALUES($1,'operator')",[sender]);
await db.query("INSERT INTO academy_messages(room_slug,user_id,body) VALUES('trade-floor',$1,'Hello')",[sender]);
const recipients=(await db.query('SELECT user_id FROM academy_notifications ORDER BY user_id')).rows.map(r=>r.user_id);
assert.deepEqual(recipients,[free,paid],'free and paid chat recipients, no sender/muted/banned');
assert.equal((await db.query('SELECT * FROM notification_push_jobs')).rows.length,2,'one durable job per eligible device');
await db.query("INSERT INTO academy_messages(room_slug,user_id,body) VALUES('daily-setups',$1,'Signal')",[sender]);
assert.deepEqual((await db.query("SELECT user_id FROM academy_notifications WHERE title='New signal'")).rows.map(r=>r.user_id),[paid]);
await db.query("INSERT INTO pulse_spy_events VALUES('now',extract(epoch FROM now())*1000,'5',$1)",[{kind:'entered',side:'demand',lower:600,upper:602}]);
assert.deepEqual((await db.query("SELECT user_id FROM academy_notifications WHERE type='pulse_zone' ORDER BY user_id")).rows.map(r=>r.user_id),[sender,paid]);
await db.query("INSERT INTO pulse_spy_events VALUES('old',extract(epoch FROM now()-interval '1 hour')*1000,'5',$1)",[{kind:'entered'}]);
await db.query("INSERT INTO pulse_spy_events VALUES('holding',extract(epoch FROM now())*1000,'5',$1)",[{kind:'holding'}]);
assert.equal((await db.query("SELECT * FROM academy_notifications WHERE type='pulse_zone'")).rows.length,2,'no stale or holding alerts');
await db.query("SELECT set_config('request.jwt.claim.sub',$1,false)",[free]);
await assert.rejects(()=>db.query("INSERT INTO academy_messages(room_slug,user_id,body) VALUES('trade-floor',$1,'@everyone hi')",[free]));
await assert.rejects(()=>db.query("SELECT create_mention_notifications('CEO','trade-floor','invented',ARRAY[]::uuid[],true)"));
await db.query("SELECT set_config('request.jwt.claim.sub','',false)");
const claimed=(await db.query('SELECT * FROM claim_vault_push_jobs(50)')).rows;
assert.equal(claimed.length,5);
assert.equal((await db.query('SELECT * FROM claim_vault_push_jobs(50)')).rows.length,0,'exclusive active leases');
const job=claimed.find(j=>j.user_id===free);
assert.equal((await db.query("SELECT finish_vault_push_job($1,gen_random_uuid(),'sent') AS ok",[job.id])).rows[0].ok,false,'stale lease rejected');
assert.equal((await db.query("SELECT finish_vault_push_job($1,$2,'retry') AS ok",[job.id,job.claim_token])).rows[0].ok,true);
assert.equal((await db.query('SELECT * FROM claim_vault_push_jobs(50)')).rows.length,0,'retry backoff');
await db.query("UPDATE notification_push_jobs SET available_at=now()-interval '1 second' WHERE id=$1",[job.id]);
const retry=(await db.query('SELECT * FROM claim_vault_push_jobs(50)')).rows[0];
assert.equal(retry.attempts,2);assert.notEqual(retry.claim_token,job.claim_token);
await db.query('UPDATE user_preferences SET notifications_enabled=false WHERE user_id=$1',[free]);
assert.equal((await db.query('SELECT vault_notification_deliverable($1,$2) AS ok',[job.notification_id,free])).rows[0].ok,false,'mute rechecked after enqueue');
const paidjob=claimed.find(j=>j.user_id===paid && j.notification_id!==job.notification_id);
await db.query('UPDATE profiles SET is_banned=true WHERE user_id=$1',[paid]);
assert.equal((await db.query('SELECT vault_notification_deliverable($1,$2) AS ok',[paidjob.notification_id,paid])).rows[0].ok,false,'ban rechecked after enqueue');
await db.query("INSERT INTO academy_notifications(type,title,body,link_path) VALUES('live_now','Live','Join','/academy/live')");
assert.deepEqual((await db.query("SELECT user_id FROM academy_notifications WHERE type='live_now'")).rows.map(r=>r.user_id),[sender],'live broadcast individual and paid');
await db.exec('SET ROLE authenticated');
await assert.rejects(()=>db.query('SELECT * FROM claim_vault_push_jobs(50)'));
await assert.rejects(()=>db.query('SELECT * FROM notification_push_jobs'));
await db.exec('RESET ROLE');
await db.close();
console.log('PASS: free/paid chat, Pulse freshness, mute/ban, no self alerts, broadcast permissions, durable queue, exclusive claims, fencing, retries and service-only access.');
